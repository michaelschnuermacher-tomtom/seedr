#!/usr/bin/env python3
"""Creates the app's photos from the originals in img/.

Run after adding or changing photos:  python3 tools/optimize-photos.py
Writes src/ui/photos/*.jpg (max 1200 px, no metadata, so no GPS location) and
src/ui/photo-list.js. Needs Pillow; the originals in img/ are not committed.
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'img'
TARGET = ROOT / 'src' / 'ui' / 'photos'
TOURNAMENT_PHOTO = '13-sunset-court-group.jpg'
LONG_SIDE = 1200
# Per-photo crops (left, top, right, bottom) in source pixels, e.g. a blurred edge strip.
CROPS = {'13-sunset-court-group.jpg': (52, 0, 640, 640)}
# Where the banner should look: the faces, or the subject if there are none.
# (x, y) as fractions of the photo, set by eye; the banner keeps this point visible.
FOCUS = {
    '01-terrace-pair-night.jpg': (0.50, 0.28),
    '02-terrace-woman-and-girl.jpg': (0.45, 0.33),
    '03-sunset-terrace.jpg': (0.50, 0.50),
    '04-terrace-relaxing.jpg': (0.45, 0.36),
    '05-paddling-pool-by-court.jpg': (0.63, 0.42),
    '06-lounge-group.jpg': (0.50, 0.35),
    '07-court-group-palms.jpg': (0.50, 0.45),
    '08-cocktails-selfie.jpg': (0.40, 0.35),
    '09-terrace-drinks-night.jpg': (0.47, 0.27),
    '10-court-two-players-cheering.jpg': (0.47, 0.20),
    '11-court-from-above.jpg': (0.50, 0.45),
    '12-court-selfie-beers.jpg': (0.55, 0.45),
    '13-sunset-court-group.jpg': (0.50, 0.42),
    '14-terrace-group-with-racket.jpg': (0.50, 0.26),
}

TARGET.mkdir(parents=True, exist_ok=True)
for old in TARGET.glob('*.jpg'):
    old.unlink()

names = []
info = {}
for src in sorted(SOURCE.glob('*.jpg')):
    image = ImageOps.exif_transpose(Image.open(src)).convert('RGB')
    if src.name in CROPS:
        image = image.crop(CROPS[src.name])
    image.thumbnail((LONG_SIDE, LONG_SIDE), Image.LANCZOS)
    # Saving without exif=... drops all metadata, including GPS coordinates.
    image.save(TARGET / src.name, 'JPEG', quality=70, optimize=True, progressive=True)
    names.append(src.name)
    fx, fy = FOCUS.get(src.name, (0.5, 0.4))
    info[src.name] = (fx, fy, image.width, image.height)
    print(f'{src.name}: {image.width}x{image.height}, {(TARGET / src.name).stat().st_size // 1024} KB')

if TOURNAMENT_PHOTO not in names:
    raise SystemExit(f'{TOURNAMENT_PHOTO} not found in img/')
listing = ',\n'.join(f"  'photos/{n}'" for n in names)
(ROOT / 'src' / 'ui' / 'photo-list.js').write_text(
    '// Generated by tools/optimize-photos.py — do not edit by hand.\n'
    f'export const PHOTOS = [\n{listing},\n];\n\n'
    f"export const TOURNAMENT_PHOTO = 'photos/{TOURNAMENT_PHOTO}';\n\n"
    '// Focus point (x, y as fractions) and size in pixels of each photo.\n'
    'export const PHOTO_INFO = {\n'
    + ''.join(f"  'photos/{n}': [{fx}, {fy}, {w}, {h}],\n" for n, (fx, fy, w, h) in info.items())
    + '};\n')
